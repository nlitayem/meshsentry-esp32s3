#!/usr/bin/env python3
"""Write paper/footprint.tex from `idf.py size-components --format json2`.

Usage (in an ESP-IDF shell, after tools/build_all.sh node sink):
    python tools/footprint_tex.py ../paper/footprint.tex
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.dirname(HERE)


def size_json(role, what):
    cmd = ["idf.py", "-B", f"build_{role}", "-D",
           f"SDKCONFIG=build_{role}/sdkconfig", what, "--format", "json2"]
    out = subprocess.run(cmd, cwd=FW, capture_output=True, text=True,
                         check=True).stdout
    return json.JSONDecoder().raw_decode(out[out.index("{"):])[0]


def comp(data, lib):
    for name, v in data.items():
        if name.endswith(lib):
            mem = v["memory_types"]
            code = mem.get("Flash Code", {}).get("size", 0)
            ro = mem.get("Flash Data", {}).get("size", 0)
            ram = mem.get("DIRAM", {}).get("size", 0) + mem.get("IRAM", {}).get("size", 0)
            return code, ro, ram
    return 0, 0, 0


def main(out):
    node = size_json("node", "size-components")
    sink = size_json("sink", "size-components")
    img = size_json("node", "size")
    ids_n, ids_s, mesh_n = comp(node, "libids.a"), comp(sink, "libids.a"), comp(node, "libmesh.a")
    layout = {m["name"]: m for m in img["layout"]}
    def used(key):
        return layout.get(key, {}).get("used", 0)
    img_code, img_ro = used("Flash Code"), used("Flash Data")
    # static RAM = DIRAM .data/.bss (+ code placed in IRAM/DIRAM)
    img_ram = used("DIRAM") + used("IRAM")
    f = lambda v: f"{v:,}".replace(",", "\\,")
    lines = [
        "% generated by firmware/tools/footprint_tex.py -- do not edit",
        f"\\newcommand{{\\FPIdsNodeCode}}{{{f(ids_n[0])}}}",
        f"\\newcommand{{\\FPIdsNodeRo}}{{{f(ids_n[1])}}}",
        f"\\newcommand{{\\FPIdsNodeRam}}{{{f(ids_n[2])}}}",
        f"\\newcommand{{\\FPIdsSinkCode}}{{{f(ids_s[0])}}}",
        f"\\newcommand{{\\FPIdsSinkRo}}{{{f(ids_s[1])}}}",
        f"\\newcommand{{\\FPIdsSinkRam}}{{{f(ids_s[2])}}}",
        f"\\newcommand{{\\FPMeshNodeCode}}{{{f(mesh_n[0])}}}",
        f"\\newcommand{{\\FPMeshNodeRo}}{{{f(mesh_n[1])}}}",
        f"\\newcommand{{\\FPMeshNodeRam}}{{{f(mesh_n[2])}}}",
        f"\\newcommand{{\\FPImgCode}}{{{f(img_code)}}}",
        f"\\newcommand{{\\FPImgRo}}{{{f(img_ro)}}}",
        f"\\newcommand{{\\FPImgRam}}{{{f(img_ram)}}}",
        f"\\newcommand{{\\FPIdsNodeFlash}}{{{(ids_n[0] + ids_n[1]) / 1024:.1f}}}",
    ]
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(FW, "..", "paper", "footprint.tex"))
