#!/usr/bin/env python3
"""Generate testbed key material for MeshSentry.

Writes a C header with
  * MS_NET_KEY     256-bit network HMAC key shared by all members
  * MS_SINK_PUB    sink ECDSA-P256 public key (uncompressed, 65 bytes)
  * MS_SINK_PRIV   sink private scalar (compiled into the sink only)

Pure Python (no third-party packages) so it runs inside the ESP-IDF build.
For deployments, provision keys per device (e.g. HMAC peripheral / eFuse key
blocks and the Digital Signature peripheral) instead of compiling them in.
"""
import secrets
import sys

# NIST P-256 domain parameters
P = 0xFFFFFFFF00000001000000000000000000000000FFFFFFFFFFFFFFFFFFFFFFFF
A = P - 3
N = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551
G = (0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296,
     0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5)


def add(p1, p2):
    if p1 is None:
        return p2
    if p2 is None:
        return p1
    if p1[0] == p2[0] and (p1[1] + p2[1]) % P == 0:
        return None
    if p1 == p2:
        lam = (3 * p1[0] * p1[0] + A) * pow(2 * p1[1], -1, P) % P
    else:
        lam = (p2[1] - p1[1]) * pow(p2[0] - p1[0], -1, P) % P
    x = (lam * lam - p1[0] - p2[0]) % P
    return x, (lam * (p1[0] - x) - p1[1]) % P


def mul(k, pt):
    acc = None
    while k:
        if k & 1:
            acc = add(acc, pt)
        pt = add(pt, pt)
        k >>= 1
    return acc


def c_array(name, data):
    body = ", ".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[{len(data)}] = {{ {body} }};\n"


def main(out):
    net = secrets.token_bytes(32)
    d = secrets.randbelow(N - 1) + 1
    qx, qy = mul(d, G)
    pub = b"\x04" + qx.to_bytes(32, "big") + qy.to_bytes(32, "big")
    with open(out, "w") as f:
        f.write("/* Generated by tools/gen_keys.py -- testbed keys, do not commit */\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(c_array("MS_NET_KEY", net))
        f.write(c_array("MS_SINK_PUB", pub))
        f.write("#ifdef CONFIG_MS_ROLE_SINK\n")
        f.write(c_array("MS_SINK_PRIV", d.to_bytes(32, "big")))
        f.write("#endif\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    import os
    path = sys.argv[1] if len(sys.argv) > 1 else "keys/mesh_keys.h"
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    main(path)
